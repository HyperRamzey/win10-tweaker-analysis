def parse_il(buf, off, size):
    """Walk IL; return (ok, consumed, nins, badtokens)."""
    end = off + size
    p = off
    nins = 0
    badtok = 0
    while p < end:
        op = buf[p]; p += 1
        if op == 0xFE:
            if p >= end: return False, p - off, nins, badtok
            op2 = buf[p]; p += 1
            kind = OP2.get(op2)
            if kind is None: return False, p - off, nins, badtok
        else:
            kind = OP1.get(op, -1)
            if kind == -1: return False, p - off, nins, badtok
        if kind == NONE: pass
        elif kind == I1: p += 1
        elif kind == I4: p += 4
        elif kind == I8: p += 8
        elif kind == R4: p += 4
        elif kind == R8: p += 8
        elif kind == TOK:
            if p + 4 > end: return False, p - off, nins, badtok
            tok = struct.unpack_from('<I', buf, p)[0]; p += 4
            tbl = tok >> 24
            if tbl not in VALID_TOK or (tok & 0xFFFFFF) >= MAXTOK.get(tbl, 0x1000000):
                badtok += 1
        elif kind == SW:
            if p + 4 > end: return False, p - off, nins, badtok
            n = struct.unpack_from('<I', buf, p)[0]; p += 4
            if n > 0x10000: return False, p - off, nins, badtok
            p += 4 * n
        if p > end: return False, p - off, nins, badtok
        nins += 1
    return p == end, p - off, nins, badtok

results = {}
detail = []
for rva in rvas:
    best = None
    for delta in range(-32, 17):
        h = rva + delta
        if h < 0 or h >= MEMLEN: continue
        cands = []
        b0 = mem[h]
        if b0 & 3 == 2:
            cs = b0 >> 2
            if cs > 0: cands.append((1, cs, 0, 0, 8))
        elif b0 & 3 == 3:
            if h + 12 > MEMLEN: continue
            fs = struct.unpack_from('<H', mem, h)[0]
            if (fs >> 12) == 3:
                ms = struct.unpack_from('<H', mem, h + 2)[0]
                cs = struct.unpack_from('<I', mem, h + 4)[0]
                lv = struct.unpack_from('<I', mem, h + 8)[0]
                if 0 < cs < 0x100000 and ms < 0x800 and (lv == 0 or (lv >> 24) == 0x11):
                    cands.append((12, cs, ms, lv, 8))
        for hdr, cs, ms, lv, _ in cands:
            if h + hdr + cs > MEMLEN: continue
            ok, consumed, nins, badtok = parse_il(mem, h + hdr, cs)
            if ok and badtok == 0 and nins > 0:
                score = 1000 - abs(delta)
                if mem[h + hdr + cs - 1] == 0x2A: score += 50
                best = (score, delta, hdr, cs, ms, lv, nins)
                break
        if best: break
    results[rva] = best

